/******************************************************************************
Function Name: Sci_CrcCaculate
--------------------------------------
Function Descriptions   :
Parameter Name list :
ReturnTyp           :
Refer doctuments        :
******************************************************************************/
Uint16 Sci_CrcCaculate(Uint16 *DataFirstAddPtr,Uint16 uiDataLength)
{
    Uint16 uiTemp;
    Uint16 uiCRCWord = 0xFFFF;

    while (uiDataLength--)
    {
        uiTemp = (*DataFirstAddPtr++ ^ uiCRCWord) & 0x00FF;
        uiCRCWord >>= 8;
        uiCRCWord ^= uiCRCTable[uiTemp];
    }
    return uiCRCWord;
}

