    //③、PV1、PV2折算
    if((ePvLose != g_SystemInfo.Source.bit.Pv1) && (ePvLose != g_SystemInfo.Source.bit.Pv2))
    {
        stPowerConver.fPPv1_Conver = ((s_wPVPowerConversion * fP_Pv1) / s_wPVPowerTotal);
        stPowerConver.fPPv2_Conver = s_wPVPowerConversion - stPowerConver.fPPv1_Conver;
    }
    else if(ePvLose == g_SystemInfo.Source.bit.Pv1)
    {
        stPowerConver.fPPv1_Conver = 0;
        stPowerConver.fPPv2_Conver = s_wPVPowerConversion;
    }
    else
    {
        stPowerConver.fPPv1_Conver = s_wPVPowerConversion;
        stPowerConver.fPPv2_Conver = 0;
    }

    //-----------------------------
    // 5、折算电流
    if(stValue.fRmsReal.VGridA < 60 || stPowerConver.fPGrid_Conver == 0)
    { stPowerConver.fIGrid_Conver = 0; }
    else
    { stPowerConver.fIGrid_Conver = stPowerConver.fPGrid_Conver / stValue.fRmsReal.VGridA; }

    if(stValue.fRmsReal.VGenA < 60 || stPowerConver.fPGen_Conver == 0)
    { stPowerConver.fIGen_Conver = 0; }
    else
    { stPowerConver.fIGen_Conver = stPowerConver.fPGen_Conver / stValue.fRmsReal.VGenA; }

    if(stValue.fAveReal.VBat < 10 || stPowerConver.fPBat_Conver == 0)
    { stPowerConver.fIBat_Conver = 0; }
    else
    { stPowerConver.fIBat_Conver = stPowerConver.fPBat_Conver / stValue.fAveReal.VBat; }

