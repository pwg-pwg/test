union DISPLAY_STATUS_TABLE
{
	struct DISPLAY_STATUS_BIT_FEILD
	{
		// BIT0-3
		INT16U bRsvd1:4;
		
		// BIT4-7
		INT16U bRsvd2:4;
		
		// BIT8-11
		INT16U bRsvd3:4;
		
		// BIT12-15
		INT16U bRsvd4:4;
	} bits;
	INT16U data;
} fDisplayJob;

/********************************************************************************
* Internal routine prototypes													*
********************************************************************************/
void	sDisplayJobInit(void);
INT16U	uwDisplayCount = 0;

/********************************************************************************
* Routines' implementations														*
********************************************************************************/
void	sDisplayJob(void)
{
	INT16U	wEvent;
	
	sDisplayJobInit();
	
	while(1)
	{
		wEvent = OSEventPend();
		
		if(wEvent & (1 << eDisplayTimer))
		{
		    uwDisplayCount++;
		}
	}
}

void	sDisplayJobInit(void)
{
	fDisplayJob.data = 0;
}

